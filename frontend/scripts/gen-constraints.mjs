import { readFileSync, writeFileSync } from "node:fs";

const [input, output] = process.argv.slice(2);
if (!input || !output) {
  console.error("usage: gen-constraints.mjs <openapi.json> <constraints.ts>");
  process.exit(1);
}

const { schemas } = JSON.parse(readFileSync(input, "utf8")).components;
const tag = schemas.Tag;
const tags = schemas.Tags;
if (typeof tag?.pattern !== "string" || !Number.isInteger(tag?.maxLength)) {
  console.error("openapi.json: components.schemas.Tag needs pattern and maxLength");
  process.exit(1);
}
if (!Number.isInteger(tags?.maxItems)) {
  console.error("openapi.json: components.schemas.Tags needs maxItems");
  process.exit(1);
}

writeFileSync(
  output,
  `// Generated by scripts/gen-constraints.mjs from openapi.json. Do not edit.
export const TAG_PATTERN = ${JSON.stringify(tag.pattern)};
export const TAG_MAX_LENGTH = ${tag.maxLength};
export const TAGS_MAX_ITEMS = ${tags.maxItems};
`,
);
