def _normalize(sql: str) -> str:
    return " ".join(sql.split())


def _ignore_serial(
    context,
    inspected_column,
    metadata_column,
    inspected_type,
    metadata_type,
):  # noqa: ANN001, ARG001
    # PostgreSQL reports a serial column as INTEGER with a sequence default
    if isinstance(metadata_type, models.Serial):
        return False
    return None


async def test_models_match_the_migrated_schema():
    def diff(conn: Connection) -> list:
        context = MigrationContext.configure(
            conn,
            opts={"compare_type": _ignore_serial, "compare_server_default": False},
        )
        return compare_metadata(context, models.metadata)

    async with database.engine.connect() as conn:
        assert await conn.run_sync(diff) == []


async def test_alembic_check_reports_only_the_serial_column_current_behaviour():
    with pytest.raises(AutogenerateDiffsDetected) as exc_info:
        await asyncio.to_thread(command.check, migration_helpers.alembic_config())

    # a false positive: env.py does not teach the comparison about models.Serial
    message = str(exc_info.value)
    assert message.count("modify_type") == 1
    assert "'notes', 'note_number'" in message
    assert "add_" not in message
    assert "remove_" not in message


async def test_note_number_is_a_serial_owned_by_its_sequence():
    default = await helpers.scalar(
        "SELECT column_default FROM information_schema.columns "
        "WHERE table_name = 'notes' AND column_name = 'note_number'",
    )
    owner = await helpers.scalar("SELECT pg_get_serial_sequence('notes', 'note_number')")

    assert default == "nextval('notes_note_number_seq'::regclass)"
    assert owner == "public.notes_note_number_seq"


def test_application_matview_query_is_the_latest_migration_definition():
    assert _normalize(database.REPEAT_NOTES_MATVIEW_QUERY) == _normalize(
        REPEAT_NOTES_MATVIEW_V2,
    )


def test_first_matview_definition_differs_only_in_reading_the_statuses_table():
    v1_only = set(_normalize_lines(REPEAT_NOTES_MATVIEW)) - set(
        _normalize_lines(REPEAT_NOTES_MATVIEW_V2),
    )
    v2_only = set(_normalize_lines(REPEAT_NOTES_MATVIEW_V2)) - set(
        _normalize_lines(REPEAT_NOTES_MATVIEW),
    )

    assert v1_only == {
        "WHEN s IS NULL THEN 'queue'",
        "WHEN s.completed_at IS NULL THEN 'reading'",
        "LEFT JOIN statuses s ON s.material_id = m.material_id",
        "LEFT JOIN last_material_repeat r ON r.material_id = s.material_id",
    }
    assert v2_only == {
        "WHEN m.started_at IS NULL THEN 'queue'",
        "WHEN m.completed_at IS NULL THEN 'reading'",
        "LEFT JOIN last_material_repeat r",
        "ON r.material_id = m.material_id AND m.started_at IS NOT NULL",
    }


def _normalize_lines(sql: str) -> list[str]:
    return [_normalize(line) for line in sql.splitlines() if line.strip()]


async def test_migrated_matview_is_what_the_application_query_creates():
    def definitions(conn: Connection) -> tuple[str, str]:
        view_definition = sa.text("SELECT pg_get_viewdef('mvw_repeat_notes'::regclass)")
        migrated = conn.scalar(view_definition)
        conn.execute(sa.text("DROP MATERIALIZED VIEW mvw_repeat_notes"))
        conn.execute(sa.text(database.REPEAT_NOTES_MATVIEW_QUERY))
        return migrated, conn.scalar(view_definition)

    migrated, from_application = await in_rolled_back_migration(definitions)

    assert migrated == from_application
    assert "statuses" not in migrated


async def test_migrated_matview_is_populated_and_empty_on_a_new_database():
    populated = await helpers.scalar(
        "SELECT ispopulated FROM pg_matviews WHERE matviewname = 'mvw_repeat_notes'",
    )

    assert populated is True
    assert await helpers.fetch_all("SELECT * FROM mvw_repeat_notes") == []


async def test_sort_key_columns_use_the_c_collation_and_are_unique():
    rows = await helpers.fetch_all(
        "SELECT table_name, collation_name FROM information_schema.columns "
        "WHERE column_name = 'sort_key' ORDER BY table_name",
    )
    schema = await migration_helpers.schema_snapshot()

    assert [tuple(row) for row in rows] == [
        ("cards", "C"),
        ("materials", "C"),
        ("notes", "C"),
        ("reading_log", "C"),
    ]
    for table in ("cards", "materials", "notes", "reading_log"):
        assert schema[table]["unique"][f"{table}_sort_key_key"] == ("sort_key",)
